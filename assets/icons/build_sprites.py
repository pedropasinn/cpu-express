"""Turns the 16 x 16 SVG icons of this folder into `src/ui_sprites.rs`.

Run from the project root after adding or changing an icon:

    python assets/icons/build_sprites.py

The game embeds the generated table; it never reads SVG or image files at run time.
If Python cannot run on the host, build_sprites.cjs emits the same table with Node.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent.parent / "src" / "ui_sprites.rs"
RECT = re.compile(r"<rect\s+([^>]*?)/?>")
ATTR = re.compile(r"(\w+)='([^']*)'|(\w+)=\"([^\"]*)\"")


def parse(path):
    rects = []
    for body in RECT.findall(path.read_text(encoding="utf-8")):
        attrs = {}
        for a, b, c, d in ATTR.findall(body):
            attrs[a or c] = b if a else d
        x, y, w, h = (int(attrs[k]) for k in ("x", "y", "width", "height"))
        fill = attrs["fill"].lstrip("#")
        if not (0 <= x and 0 <= y and w > 0 and h > 0 and x + w <= 16 and y + h <= 16 and len(fill) == 6):
            sys.exit(f"{path.name}: rectangle outside the 16 x 16 grid or bad colour")
        rects.append((x, y, w, h, int(fill[0:2], 16), int(fill[2:4], 16), int(fill[4:6], 16)))
    if not rects:
        sys.exit(f"{path.name}: no rectangles")
    return rects


def variant(name):
    return "".join(part.capitalize() for part in name.split("-"))


icons = sorted(p for p in HERE.glob("*.svg") if p.stem != "preview")
lines = [
    "//! Generated by `assets/icons/build_sprites.py` from the SVG icons; do not edit by hand.",
    "//! Original 16 x 16 pixel art in the game palette, embedded as coloured rectangles.",
    "",
    "/// One coloured rectangle of a sprite: x, y, width, height on the 16 x 16 grid, then RGB.",
    "pub type Cell = (u8, u8, u8, u8, u8, u8, u8);",
    "",
    "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
    "pub enum Sprite {",
]
lines += [f"    {variant(p.stem)}," for p in icons]
lines += ["}", "", "impl Sprite {", f"    pub const ALL: [Self; {len(icons)}] = ["]
lines += [f"        Self::{variant(p.stem)}," for p in icons]
lines += ["    ];", "", "    /// File name of the source icon, without extension.", "    #[must_use]",
          "    pub const fn name(self) -> &'static str {", "        match self {"]
lines += [f"            Self::{variant(p.stem)} => \"{p.stem}\"," for p in icons]
lines += ["        }", "    }", "", "    #[must_use]", "    pub const fn cells(self) -> &'static [Cell] {", "        match self {"]
lines += [f"            Self::{variant(p.stem)} => &{p.stem.upper().replace('-', '_')}," for p in icons]
lines += ["        }", "    }", "}", ""]
for p in icons:
    cells = parse(p)
    lines.append(f"const {p.stem.upper().replace('-', '_')}: [Cell; {len(cells)}] = [")
    lines += [f"    ({x}, {y}, {w}, {h}, {r}, {g}, {b})," for x, y, w, h, r, g, b in cells]
    lines += ["];", ""]
OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{len(icons)} sprites -> {OUT}")
