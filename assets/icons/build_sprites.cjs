// Dependency-free fallback for build_sprites.py on hosts without usable Python.
// Keep output byte-compatible with the canonical Python generator (before rustfmt).
const fs=require('node:fs'), path=require('node:path');
const icons=fs.readdirSync(__dirname).filter(p=>p.endsWith('.svg')&&p!=='preview.svg').sort().map(p=>p.slice(0,-4));
const variant=n=>n.split('-').map(p=>p[0].toUpperCase()+p.slice(1).toLowerCase()).join('');
const constant=n=>n.toUpperCase().replaceAll('-','_');
function parse(name) {
 const svg=fs.readFileSync(path.join(__dirname,name+'.svg'),'utf8');
 const cells=[...svg.matchAll(/<rect\s+([^>]*?)\/?>/g)].map(m=>{
   const a=Object.fromEntries([...m[1].matchAll(/(\w+)='([^']*)'|(\w+)="([^"]*)"/g)].map(m=>[m[1]||m[3],m[1]?m[2]:m[4]]));
   const [x,y,w,h]=['x','y','width','height'].map(k=>Number(a[k]));
   if(![x,y,w,h].every(Number.isInteger)||x<0||y<0||w<=0||h<=0||x+w>16||y+h>16||!/^#[0-9a-f]{6}$/i.test(a.fill)) throw Error(name+': retângulo inválido');
   return [x,y,w,h,...[1,3,5].map(i=>parseInt(a.fill.slice(i,i+2),16))];
 });
 if(!cells.length) throw Error(name+': sprite vazio');
 return cells;
}
const lines=[
 '//! Generated by `assets/icons/build_sprites.py` from the SVG icons; do not edit by hand.',
 '//! Original 16 x 16 pixel art in the game palette, embedded as coloured rectangles.',
 '', '/// One coloured rectangle of a sprite: x, y, width, height on the 16 x 16 grid, then RGB.',
 'pub type Cell = (u8, u8, u8, u8, u8, u8, u8);','',
 '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]','pub enum Sprite {',
 ...icons.map(n=>`    ${variant(n)},`),'}','','impl Sprite {',`    pub const ALL: [Self; ${icons.length}] = [`,
 ...icons.map(n=>`        Self::${variant(n)},`),'    ];','',
 '    /// File name of the source icon, without extension.','    #[must_use]',"    pub const fn name(self) -> &'static str {",'        match self {',
 ...icons.map(n=>`            Self::${variant(n)} => "${n}",`),'        }','    }','',
 '    #[must_use]',"    pub const fn cells(self) -> &'static [Cell] {",'        match self {',
 ...icons.map(n=>`            Self::${variant(n)} => &${constant(n)},`),'        }','    }','}',''];
for(const name of icons) { const cells=parse(name); lines.push(`const ${constant(name)}: [Cell; ${cells.length}] = [`,...cells.map(c=>`    (${c.join(', ')}),`),'];',''); }
fs.writeFileSync(path.resolve(__dirname,'../../src/ui_sprites.rs'),lines.join('\n'));
console.log(`${icons.length} sprites -> src/ui_sprites.rs (alternativa Node)`);
